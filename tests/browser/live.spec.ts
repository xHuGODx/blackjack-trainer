import { test, expect } from '@playwright/test';
test('rapid counting, integrated hand, EV worker, clear and reload', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByTestId('running-count')).toHaveText('0');
  await page.keyboard.press('2'); await page.keyboard.press('3'); await page.keyboard.press('4');
  await expect(page.getByTestId('cards-seen')).toHaveText('3');
  await expect(page.getByTestId('running-count')).toHaveText('+3');
  await page.keyboard.press('Backspace');
  await expect(page.getByTestId('cards-seen')).toHaveText('2');
  await page.keyboard.press('Control+Shift+Z');
  await expect(page.getByTestId('cards-seen')).toHaveText('3');
  await page.keyboard.press('p'); await page.keyboard.press('5'); await page.keyboard.press('6');
  await page.keyboard.press('d'); await page.keyboard.press('6');
  await expect(page.locator('.recommendation h3')).toHaveText('Double down');
  await expect(page.locator('.ev-actions')).toContainText('+0.', { timeout: 10_000 });
  await expect(page.locator('.ev-actions')).not.toContainText('…', { timeout: 10_000 });
  await expect(page.getByTestId('cards-seen')).toHaveText('6');
  await page.getByRole('button', { name: 'Clear current hand' }).click();
  await expect(page.locator('.recommendation h3')).toHaveText('Your next move');
  await expect(page.getByTestId('cards-seen')).toHaveText('6');
  const persistence = await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }));
  expect(persistence).toEqual({ local: 0, session: 0 });
  await page.reload();
  await expect(page.getByTestId('cards-seen')).toHaveText('0');
  await expect(page.getByRole('button', { name: 'Undo last action' })).toBeDisabled();
  expect(errors).toEqual([]);
});
