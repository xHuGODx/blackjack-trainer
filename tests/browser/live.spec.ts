test('grouped tens, custom tag uncertainty and switching systems retain the shoe', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('checkbox', { name: 'Combine 10s', exact: true }).check();
  await page.keyboard.press('0'); await page.keyboard.press('t');
  await expect(page.getByTestId('cards-seen')).toHaveText('2');
  await expect(page.getByTestId('running-count')).toHaveText('-2');
  await expect(page.locator('.shoe-panel')).toContainText('2 ten-value cards entered without a face');
  await page.locator('.inline-select select').selectOption('Hi-Opt II');
  await expect(page.getByTestId('running-count')).toHaveText('-4');
  await expect(page.getByTestId('cards-seen')).toHaveText('2');
  await page.getByRole('button', { name: 'Table rules', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Counting system', { exact: true }).selectOption('Custom');
  await page.getByLabel('Custom tag J', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Back to the table' }).click();
  await expect(page.getByTestId('running-count')).toHaveText('—');
  await expect(page.locator('.error-banner[role="alert"]')).toContainText('Grouped ten-value cards');
  await page.getByRole('button', { name: 'New shoe' }).click();
  await expect(page.getByTestId('cards-seen')).toHaveText('0');
});
test('all narrow and tablet widths avoid horizontal overflow; large/compact modes work', async ({ page }) => {
  await page.goto('/');
  for (const width of [320, 393, 620, 768, 1000, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), `overflow at ${width}`).toBe(false);
  }
  await page.getByRole('button', { name: 'Table rules', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Compact layout', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Larger card buttons', exact: true }).check();
  await page.getByRole('button', { name: 'Back to the table' }).click();
  await page.setViewportSize({ width: 393, height: 851 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await expect(page.locator('.mobile-livebar')).toBeVisible();
  await page.locator('.mobile-livebar').getByRole('button', { name: 'MY HAND' }).click();
  await expect(page.locator('.input-destination')).toContainText('your hand');
});
