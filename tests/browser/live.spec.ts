test('already-counted and preview cards do not affect the live counter twice', async ({ page }) => {
  await page.goto('/');
  await page.locator('#bulk-cards').fill('A 10 6');
  await page.getByRole('button', { name: 'Add cards', exact: true }).click();
  await expect(page.getByTestId('cards-seen')).toHaveText('3');
  await page.keyboard.press('p');
  await page.getByLabel('Card registration').selectOption('already');
  await page.getByRole('button', { name: 'Add A to player', exact: true }).click();
  await page.getByRole('button', { name: 'Add 10 to player', exact: true }).click();
  await expect(page.getByTestId('cards-seen')).toHaveText('3');
  await page.keyboard.press('d');
  await page.getByRole('button', { name: 'Add 6 to dealer', exact: true }).click();
  await expect(page.locator('.recommendation h3')).toHaveText('Stand');
  await expect(page.locator('.ev-actions')).toContainText('+1.5000');
  await page.getByRole('button', { name: 'Clear current hand' }).click();
  await page.keyboard.press('p');
  await page.getByLabel('Card registration').selectOption('preview');
  await page.getByRole('button', { name: 'Add 8 to player', exact: true }).click();
  await page.getByRole('button', { name: 'Add 8 to player', exact: true }).click();
  await page.keyboard.press('d'); await page.getByRole('button', { name: 'Add 6 to dealer', exact: true }).click();
  await expect(page.locator('.recommendation h3')).toHaveText('Split');
  await expect(page.getByTestId('cards-seen')).toHaveText('3');
});
